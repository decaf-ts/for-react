/**
 * @file
 * @summary React composition of the agent chat: the @ai-sdk `useChat` state
 * machine (messages/streaming/tool parts) plus the decaf side-channel store
 * (telemetry, structured object, approval, demo panels, availability).
 * @description The React analog of the Angular `AgentChatService`. `useChat`
 * owns the transcript and drives the transport seam; this hook derives host
 * actions (`send`, `replay`, `cancel`, `editMessage`, `removeMessage`,
 * `setVote`, `reset`) and projects SDK `UIMessage`s into the
 * {@link AgentChatMessageView} read model the components render.
 */
import { useCallback, useEffect, useMemo, useState } from "react";
import { useChat } from "@ai-sdk/react";
import { getWindow } from "../../lib/utils/window.js";
import { GraphBackendUnavailableError } from "../../diagrams/execution/GraphExecutionService.js";
import { AgentChatLegacyChatTransportAdapter } from "../services/AgentChatLegacyChatTransportAdapter.js";
import type { AgentChatTransportBody } from "../services/GraphRunAgentChatTransport.js";
import type {
  AgentChatAttachment,
  AgentChatConfiguration,
  AgentChatMessagePart,
  AgentChatMessageView,
  AgentChatRole,
  AgentChatRoundtripTelemetry,
  AgentChatRunDescriptor,
  AgentChatSdkTransport,
  AgentChatSideChannelHandlers,
  AgentChatStructuredObjectEntry,
  AgentChatStructuredObjectView,
  AgentChatTransport,
  AgentChatUIMessage,
  AgentChatUIMessageMetadata,
  AgentChatVote,
} from "../types.js";
import {
  isAgentChatSdkTransport,
  useAgentChatContext,
} from "./AgentChatProvider.js";
import type {
  AgentChatApprovalView,
  AgentChatDecafState,
  AgentChatDecafStore,
  AgentChatDemoState,
} from "./agentChatStore.js";

/** SDK `UIMessage` parts projected by {@link projectParts}. */
type AgentChatUIMessageParts = AgentChatUIMessage["parts"];

/** Module-level counter backing generated session ids. */
let agentChatSessionSequence = 0;

/** Prefix for session ids generated by {@link useAgentChat}.
 * @memberOf module:for-react.agent
 */
export const AGENT_CHAT_SESSION_PREFIX = "agent-chat";

/** Options accepted by {@link useAgentChat}.
 * @memberOf module:for-react.agent
 */
export interface UseAgentChatOptions extends AgentChatConfiguration {
  /** Inline workflow document (takes precedence over `workflowId`). */
  workflow?: unknown;
  /** Transport override for this hook instance (SDK seam or legacy bridge). */
  transport?: AgentChatTransport | AgentChatSdkTransport;
}

/** Conversation surface returned by {@link useAgentChat}.
 * @memberOf module:for-react.agent
 */
export interface AgentChatController {
  /** Projected transcript messages. */
  messages: AgentChatMessageView[];
  /** Per-run telemetry rows. */
  roundtrips: AgentChatRoundtripTelemetry[];
  /** Latest structured object, or `null`. */
  structuredObject: AgentChatStructuredObjectView | null;
  /** Committed structured-object history. */
  structuredObjectHistory: AgentChatStructuredObjectEntry[];
  /** Run-level approval prompt, or `null`. */
  approval: AgentChatApprovalView | null;
  /** Demo-only panel state. */
  demo: AgentChatDemoState;
  /** Tri-state backend availability. */
  backendAvailable: boolean | null;
  /** `true` while a send/replay is in flight. */
  running: boolean;
  /** Run id of the in-flight roundtrip, or `null`. */
  activeRunId: string | null;
  /** Last surfaced error text, or `null`. */
  error: string | null;
  /** Active session id. */
  sessionId: string;
  /** Sends a user message through the SDK chat. */
  send(
    message: string,
    attachments?: AgentChatAttachment[],
    knowledgeSourceIds?: string[]
  ): Promise<void>;
  /** Replays a previously created run through the SDK resume path. */
  replay(descriptor: AgentChatRunDescriptor): Promise<void>;
  /** Stops the active run and cancels the backend run. */
  cancel(): Promise<void>;
  /** Replaces an already-sent user message and re-sends it. */
  editMessage(messageId: string, newText: string): Promise<void>;
  /** Removes one message from the local transcript. */
  removeMessage(messageId: string): void;
  /** Records or clears the user's vote on a message. */
  setVote(messageId: string, vote: AgentChatVote | null): void;
  /** Clears the conversation and every decaf-owned field. */
  reset(): void;
  /** Resolves the user id sent with requests. */
  userId(): string | null;
}

/**
 * Drives one agent chat conversation.
 *
 * @param options - Workflow/session/user configuration and an optional transport override.
 * @returns The projected transcript and host actions.
 * @memberOf module:for-react.agent
 */
export function useAgentChat(
  options: UseAgentChatOptions = {}
): AgentChatController {
  const context = useAgentChatContext();
  const store = context.store;
  const sourceTransport = options.transport ?? context.sourceTransport;

  const transport = useMemo<AgentChatSdkTransport>(
    () =>
      isAgentChatSdkTransport(sourceTransport)
        ? sourceTransport
        : new AgentChatLegacyChatTransportAdapter(sourceTransport),
    [sourceTransport]
  );

  const [generatedSessionId] = useState(
    () =>
      `${AGENT_CHAT_SESSION_PREFIX}-${Date.now()}-${++agentChatSessionSequence}`
  );
  const sessionId =
    options.sessionId && options.sessionId.length > 0
      ? options.sessionId
      : generatedSessionId;

  const sideChannel = useMemo<AgentChatSideChannelHandlers>(
    () => ({
      onTelemetry: (telemetry) => store.getState().mergeTelemetry(telemetry),
      onStructuredObject: (view) =>
        store.getState().setStructuredObject(view),
      onError: (error) => {
        store.getState().setError(errorTextOf(error));
        if (error instanceof GraphBackendUnavailableError) {
          store.getState().setBackendAvailable(false);
        }
      },
      onBackendAvailable: (available) =>
        store.getState().setBackendAvailable(available),
      onDemoEvent: (event) => store.getState().applyDemoEvent(event),
    }),
    [store]
  );

  const chat = useChat<AgentChatUIMessage>({
    id: sessionId,
    transport,
    onError: (error) => store.getState().setError(errorTextOf(error)),
  });

  const running = chat.status === "submitted" || chat.status === "streaming";

  useEffect(() => {
    const demoSource = sourceTransport as {
      subscribeDemoEvents?: (
        listener: (event: Parameters<AgentChatDecafState["applyDemoEvent"]>[0]) => void
      ) => () => void;
    };
    if (typeof demoSource.subscribeDemoEvents !== "function") return undefined;
    return demoSource.subscribeDemoEvents((event) =>
      store.getState().applyDemoEvent(event)
    );
  }, [sourceTransport, store]);

  const userId = useCallback((): string | null => {
    const configured = options.userId;
    if (configured !== undefined) return configured;
    const logged = getWindow()?.["loggedUser"] as unknown;
    return typeof logged === "string" && logged.length > 0 ? logged : null;
  }, [options.userId]);

  const requestBody = useCallback(
    (
      attachments: AgentChatAttachment[],
      knowledgeSourceIds: string[],
      descriptor?: AgentChatRunDescriptor
    ): AgentChatTransportBody => ({
      workflow: options.workflow,
      workflowId: options.workflowId ?? undefined,
      sessionId,
      userId: userId(),
      attachments,
      knowledgeSourceIds,
      ...(descriptor ? { descriptor } : {}),
    }),
    [options.workflow, options.workflowId, sessionId, userId]
  );

  const send = useCallback(
    async (
      message: string,
      attachments: AgentChatAttachment[] = [],
      knowledgeSourceIds: string[] = []
    ): Promise<void> => {
      const text = message.trim();
      if (!text || running) return;
      store.getState().setError(null);
      chat.clearError();
      const metadata: AgentChatUIMessageMetadata = {
        attachments,
        knowledgeSourceIds,
        sessionId,
        createdAt: new Date().toISOString(),
      };
      try {
        await chat.sendMessage(
          { text, metadata },
          {
            body: requestBody(attachments, knowledgeSourceIds),
            metadata: { sideChannel },
          }
        );
      } catch (error) {
        store.getState().setError(errorTextOf(error));
      }
    },
    [running, store, chat, sessionId, requestBody, sideChannel]
  );

  const replay = useCallback(
    async (descriptor: AgentChatRunDescriptor): Promise<void> => {
      if (running) return;
      store.getState().setError(null);
      chat.clearError();
      try {
        await chat.resumeStream({
          body: requestBody([], [], descriptor),
          metadata: { sideChannel },
        });
      } catch (error) {
        store.getState().setError(errorTextOf(error));
      }
    },
    [running, store, chat, requestBody, sideChannel]
  );

  const cancel = useCallback(async (): Promise<void> => {
    try {
      await chat.stop();
    } catch (error) {
      store.getState().setError(errorTextOf(error));
    }
  }, [chat, store]);

  const editMessage = useCallback(
    async (messageId: string, newText: string): Promise<void> => {
      if (running) return;
      const messages = chat.messages;
      const index = messages.findIndex((message) => message.id === messageId);
      if (index < 0) return;
      const target = messages[index];
      if (target.role !== "user") return;
      const text = newText.trim();
      if (!text) return;
      const metadata = target.metadata ?? {};
      chat.setMessages(messages.slice(0, index));
      await send(
        text,
        metadata.attachments ?? [],
        metadata.knowledgeSourceIds ?? []
      );
    },
    [running, chat, send]
  );

  const removeMessage = useCallback(
    (messageId: string): void => {
      const messages = chat.messages;
      if (!messages.some((message) => message.id === messageId)) return;
      chat.setMessages(
        messages.filter((message) => message.id !== messageId)
      );
    },
    [chat]
  );

  const setVote = useCallback(
    (messageId: string, vote: AgentChatVote | null): void => {
      let changed = false;
      const messages = chat.messages.map((message) => {
        if (message.id !== messageId) return message;
        changed = true;
        return {
          ...message,
          metadata: {
            ...(message.metadata ?? {}),
            vote,
            editedAt: new Date().toISOString(),
          },
        };
      });
      if (!changed) return;
      chat.setMessages(messages);
    },
    [chat]
  );

  const reset = useCallback((): void => {
    chat.setMessages([]);
    chat.clearError();
    store.getState().reset();
  }, [chat, store]);

  const decaf = useDecafState(store);

  const messages = useMemo(
    () => agentChatMessagesFromUI(chat.messages),
    [chat.messages]
  );

  return {
    messages,
    roundtrips: decaf.roundtrips,
    structuredObject: decaf.structuredObject,
    structuredObjectHistory: decaf.structuredObjectHistory,
    approval: decaf.approval,
    demo: decaf.demo,
    backendAvailable: decaf.backendAvailable,
    running,
    activeRunId: decaf.activeRunId,
    error: chat.error?.message ?? decaf.error,
    sessionId,
    send,
    replay,
    cancel,
    editMessage,
    removeMessage,
    setVote,
    reset,
    userId,
  };
}

/**
 * Subscribes to the full decaf store state (used by {@link useAgentChat}).
 * Kept separate so the hook's rendered fields stay in sync with the store.
 */
function useDecafState(
  store: AgentChatDecafStore
): AgentChatDecafState {
  const [state, setState] = useState<AgentChatDecafState>(() =>
    store.getState()
  );
  useEffect(() => {
    setState(store.getState());
    return store.subscribe((next) => setState(next));
  }, [store]);
  return state;
}

/** Extracts a displayable message from an unknown thrown value.
 * @memberOf module:for-react.agent
 */
export function errorTextOf(err: unknown): string {
  if (err instanceof GraphBackendUnavailableError) return err.message;
  if (err instanceof Error) return err.message;
  return String(err);
}

/** Projects SDK `UIMessage`s into the decaf read model the components render.
 * @memberOf module:for-react.agent
 */
export function agentChatMessagesFromUI(
  messages: AgentChatUIMessage[]
): AgentChatMessageView[] {
  return messages.map((message) => {
    const metadata = message.metadata ?? {};
    const errorPart = message.parts.find(
      (
        part
      ): part is {
        type: "data-error";
        data: { message: string; name?: string };
      } => part.type === "data-error"
    );
    const role: AgentChatRole =
      message.role === "user"
        ? "user"
        : message.role === "system"
          ? "system"
          : errorPart
            ? "error"
            : "assistant";
    const text = message.parts
      .filter(
        (
          part
        ): part is {
          type: "text";
          text: string;
          state?: "streaming" | "done";
        } => part.type === "text"
      )
      .map((part) => part.text)
      .join("");
    const parts = role === "assistant" ? projectParts(message.parts) : undefined;
    const streaming = message.parts.some(
      (part) =>
        (part.type === "text" || part.type === "reasoning") &&
        "state" in part &&
        part.state === "streaming"
    );
    return {
      id: message.id,
      role,
      content: role === "error" ? (errorPart?.data.message ?? "") : text,
      attachments: metadata.attachments ?? [],
      knowledgeSourceIds: metadata.knowledgeSourceIds ?? [],
      createdAt: metadata.createdAt ?? "",
      ...(metadata.runId ? { runId: metadata.runId } : {}),
      ...(parts && parts.length ? { parts } : {}),
      ...(streaming ? { streaming } : {}),
      ...(metadata.actions?.length ? { actions: metadata.actions } : {}),
      ...(metadata.vote !== undefined ? { vote: metadata.vote } : {}),
      ...(metadata.editedAt ? { editedAt: metadata.editedAt } : {}),
    };
  });
}

/** Projects SDK message parts into decaf nested parts.
 * @memberOf module:for-react.agent
 */
export function projectParts(
  parts: AgentChatUIMessageParts
): AgentChatMessagePart[] {
  const projected: AgentChatMessagePart[] = [];
  parts.forEach((part, index) => {
    const record = part as unknown as Record<string, unknown>;
    switch (record["type"]) {
      case "text":
        projected.push({
          id: `text:${index}`,
          kind: "text",
          text:
            typeof record["text"] === "string"
              ? (record["text"] as string)
              : "",
          ...(record["state"] === "streaming" ? { streaming: true } : {}),
        });
        break;
      case "reasoning":
        projected.push({
          id:
            typeof record["id"] === "string" && record["id"].length > 0
              ? (record["id"] as string)
              : `reasoning:${index}`,
          kind: "reasoning",
          content:
            typeof record["text"] === "string"
              ? (record["text"] as string)
              : "",
          ...(record["state"] === "streaming" ? { streaming: true } : {}),
        });
        break;
      case "custom":
        if (record["kind"] === "decaf.code") {
          const provider = record["providerMetadata"] as
            | { decaf?: Record<string, unknown> }
            | undefined;
          const decaf = provider?.decaf ?? {};
          projected.push({
            id: `code:${index}`,
            kind: "code",
            code:
              typeof decaf["code"] === "string"
                ? (decaf["code"] as string)
                : "",
            ...(typeof decaf["language"] === "string"
              ? { language: decaf["language"] as string }
              : {}),
            ...(typeof decaf["filename"] === "string"
              ? { filename: decaf["filename"] as string }
              : {}),
            ...(typeof decaf["title"] === "string"
              ? { title: decaf["title"] as string }
              : {}),
          });
        }
        break;
      case "file": {
        const url =
          typeof record["url"] === "string" ? (record["url"] as string) : "";
        if (!url) break;
        projected.push({
          id: `file:${index}`,
          kind: "attachment",
          attachment: {
            id: `file:${index}`,
            name: url.split("/").pop() ?? "attachment",
            mime:
              typeof record["mediaType"] === "string"
                ? (record["mediaType"] as string)
                : "application/octet-stream",
            size: 0,
            url,
          },
        });
        break;
      }
      default:
        if (
          typeof record["type"] === "string" &&
          (record["type"] as string).startsWith("tool-")
        ) {
          projected.push(projectToolPart(record, index));
        }
        break;
    }
  });
  return projected;
}

/** Projects an SDK tool part into a decaf tool part.
 * @memberOf module:for-react.agent
 */
export function projectToolPart(
  record: Record<string, unknown>,
  index: number
): AgentChatMessagePart {
  const state =
    typeof record["state"] === "string" ? (record["state"] as string) : "";
  const status =
    state === "output-available"
      ? "succeeded"
      : state === "output-error" || state === "output-denied"
        ? "failed"
        : state === "input-streaming" || state === "input-available"
          ? state === "input-available"
            ? "running"
            : "queued"
          : "running";
  const toolCallId =
    typeof record["toolCallId"] === "string"
      ? (record["toolCallId"] as string)
      : `tool:${index}`;
  const typeName = (record["type"] as string).slice("tool-".length);
  const toolName =
    typeof record["toolName"] === "string" &&
    (record["toolName"] as string).length > 0
      ? (record["toolName"] as string)
      : typeName;
  return {
    id: toolCallId,
    kind: "tool",
    name: toolName,
    status,
    ...(record["input"] !== undefined ? { input: record["input"] } : {}),
    ...(record["output"] !== undefined ? { output: record["output"] } : {}),
    ...(typeof record["errorText"] === "string"
      ? { error: record["errorText"] as string }
      : {}),
  };
}
